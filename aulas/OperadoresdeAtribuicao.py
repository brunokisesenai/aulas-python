#OPERADORES DE ATRIBUIÇÃO

# =  ->  atribui um valor à variável

# +=  ->  atribui um valor X NUMÉRICO a variável
#   Ex: idade = 18
#       idade += 2  ->  20 (incremento)

# -=  ->  subtrair um valor X NUMÉRICO a variável
#   Ex: idade = 18
#       idade -= 16  ->  20 (decremento)

# *=  ->  multiplicar um valor X NUMÉRICO a variável
#   Ex: idade = 18
#       idade *= 2  ->  36 (incremento)

# /=  ->  dividir por um valor X NUMÉRICO a variável
#   Ex: idade = 18
#       idade /= 2  ->  9 (incremento)

#EXEMPLO 1:

# idade = 10
# idade += 8 #18
# idade -= 8 #10
# idade *= 2 #20
# idade /= 2 #10